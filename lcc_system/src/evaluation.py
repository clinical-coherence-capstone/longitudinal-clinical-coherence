# ---------------------------------------------------------------------------
# Evaluator class
# ---------------------------------------------------------------------------
class Evaluator:
    """Runs baseline and LCC evaluation across all SCENARIOS."""

    def __init__(self, loader: DatasetLoader) -> None:
        self.loader = loader
        # Pre-load cases once (reproducible under the fixed seed)
        self._cases = {c.case_id: c for c in loader.generate_synthetic_cases(25)}
        self._gen = ConversationGenerator(loader)

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def run_baseline(self, scenario: TestScenario) -> dict:
        """Run pipeline WITHOUT CoherenceVerifier/DecisionGate.

        Always returns decision='PASS' (baseline never catches errors).
        """
        case = self._cases.get(scenario.source_case_id)
        if case is None:
            return {
                "decision": "PASS",
                "response_text": "[case not found]",
                "latency_ms": 0.0,
            }

        # Generate conversation for the case
        conversation = self._gen.generate_conversation(case, form="gradual_reveal")
        # Inject the scenario text
        conversation = self._inject_scenario(conversation, scenario)

        # Build pipeline components
        state_manager = StateManager(case.case_id)
        extractor = StateExtractor(self.loader.load_evidence_vocab())
        normalizer = MedicationNormalizer(self.loader)
        retriever = EvidenceRetriever(self.loader, normalizer)
        gen = ResponseGenerator(state_manager, retriever, provider="mock")

        # Process all turns through state
        for turn in conversation.turns:
            if turn.speaker == "patient":
                facts = extractor.extract_from_turn(turn, turn.turn_index)
                state_manager.update(turn.turn_index, facts)

        # Generate response once (last state)
        response_text, _ = gen.generate_response(conversation)

        # Baseline always PASS — no verifier
        return {
            "decision": "PASS",
            "response_text": response_text,
            "latency_ms": 0.0,
        }

    def run_lcc(self, scenario: TestScenario) -> dict:
        """Run full LCC pipeline with CoherenceVerifier and DecisionGate.

        Returns dict with decision, flags, response_text, latency_ms.
        """
        case = self._cases.get(scenario.source_case_id)
        if case is None:
            return {
                "decision": "PASS",
                "response_text": "[case not found]",
                "flags": [],
                "latency_ms": 0.0,
            }

        t_start = time.perf_counter()

        # Generate conversation
        conversation = self._gen.generate_conversation(case, form="gradual_reveal")
        # Inject scenario text
        conversation = self._inject_scenario(conversation, scenario)

        # Build pipeline
        state_manager = StateManager(case.case_id)
        extractor = StateExtractor(self.loader.load_evidence_vocab())
        normalizer = MedicationNormalizer(self.loader)
        retriever = EvidenceRetriever(self.loader, normalizer)
        gen = ResponseGenerator(state_manager, retriever, provider="mock")
        verifier = CoherenceVerifier(state_manager, retriever, normalizer)
        gate = DecisionGate()

        # Process all turns through state extractor + state manager
        for turn in conversation.turns:
            if turn.speaker == "patient":
                facts = extractor.extract_from_turn(turn, turn.turn_index)
                state_manager.update(turn.turn_index, facts)

        # Generate response
        response_text, evidence_used = gen.generate_response(conversation)

        # Verify and gate
        last_turn_index = len(conversation.turns) - 1
        flags = verifier.verify(response_text, evidence_used, last_turn_index, conversation)
        decision, reasoning = gate.evaluate(flags)

        t_end = time.perf_counter()
        latency_ms = (t_end - t_start) * 1000.0

        return {
            "decision": decision,
            "reasoning": reasoning,
            "response_text": response_text,
            "flags": [f.check_id for f in flags],
            "latency_ms": latency_ms,
        }

    def evaluate_all(self) -> dict:
        """Run all SCENARIOS, compute metrics, return results dict.

        Returns:
            dict with keys:
            - total: int
            - correct: int
            - detection_rate: float [0.0, 1.0]
            - false_positive_rate: float [0.0, 1.0]
            - false_negative_rate: float [0.0, 1.0]
            - mean_latency_ms: float
            - details: list[dict]
        """
        details: list[dict] = []

        for scenario in SCENARIOS:
            baseline = self.run_baseline(scenario)
            lcc = self.run_lcc(scenario)

            details.append({
                "scenario_id": scenario.scenario_id,
                "error_type": scenario.error_type,
                "expected": scenario.expected_decision,
                "baseline_decision": baseline["decision"],
                "lcc_decision": lcc["decision"],
                "lcc_flags": lcc.get("flags", []),
                "correct": lcc["decision"] == scenario.expected_decision,
                "latency_ms": lcc["latency_ms"],
            })

        # Aggregate metrics
        total = len(details)
        correct = sum(1 for d in details if d["correct"])

        error_cases = [d for d in details if d["error_type"].startswith("ERR")]
        ctrl_cases = [d for d in details if d["error_type"].startswith("CTRL")]

        # Detection rate: ERR scenarios where LCC returned non-PASS
        detected = sum(1 for d in error_cases if d["lcc_decision"] != "PASS")
        detection_rate = detected / len(error_cases) if error_cases else 0.0

        # False positive rate: CTRL scenarios where LCC returned non-PASS
        fp = sum(1 for d in ctrl_cases if d["lcc_decision"] != "PASS")
        false_positive_rate = fp / len(ctrl_cases) if ctrl_cases else 0.0

        # False negative rate: ERR scenarios where LCC returned PASS (missed)
        fn = sum(1 for d in error_cases if d["lcc_decision"] == "PASS")
        false_negative_rate = fn / len(error_cases) if error_cases else 0.0

        mean_latency_ms = sum(d["latency_ms"] for d in details) / total if total else 0.0

        return {
            "total": total,
            "correct": correct,
            "detection_rate": detection_rate,
            "false_positive_rate": false_positive_rate,
            "false_negative_rate": false_negative_rate,
            "mean_latency_ms": mean_latency_ms,
            "details": details,
        }

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _inject_scenario(
        self, conversation: Conversation, scenario: TestScenario
    ) -> Conversation:
        """Inject scenario.injection_text into the conversation.

        The injection is added as a new ConversationTurn at the given injection_turn
        index (appended after that many existing turns, or at end if index exceeds length).
        Uses injection metadata with the scenario's error_type.

        For ERR-4 (sycophancy): injected turn gets error_type='ERR-4' so that
        CoherenceVerifier._check_unsupported_belief_change can detect it.
        """
        # Deep copy to avoid mutating the shared conversation
        conv = copy.deepcopy(conversation)

        # Determine insertion position
        insert_at = min(scenario.injection_turn, len(conv.turns))

        # Determine speaker based on injection text prefix
        text = scenario.injection_text
        speaker = "patient"
        if text.lower().startswith("doctor says:") or text.lower().startswith("the doctor"):
            speaker = "doctor"
        elif text.lower().startswith("patient says:"):
            speaker = "patient"
            # Strip the "Patient says: " prefix so the text is natural
            text = text.split(":", 1)[1].strip() if ":" in text else text

        # Build injection dict
        is_err4 = scenario.error_type == "ERR-4"
        injection = {
            "is_injected": True,
            "error_type": scenario.error_type,
            "content": scenario.injection_text,
        }

        new_turn = ConversationTurn(
            turn_index=insert_at,
            speaker=speaker,
            text=text,
            revealed_evidence_ids=[],
            injection=injection,
        )

        # Re-index turns after insertion point
        conv.turns.insert(insert_at, new_turn)
        for i, t in enumerate(conv.turns):
            t.turn_index = i

        conv.current_turn = len(conv.turns)
        return conv
